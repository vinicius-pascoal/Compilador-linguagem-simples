public class ResultadoExpressao3AC {
  private final String lugar;
  private final Tipo tipo;

  public ResultadoExpressao3AC(String lugar, Tipo tipo) {
    this.lugar = lugar;
    this.tipo = tipo;
  }

  public String getLugar() {
    return lugar;
  }

  public Tipo getTipo() {
    return tipo;
  }
}
